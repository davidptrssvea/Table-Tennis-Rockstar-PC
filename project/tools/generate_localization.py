"""Generate the Windows/ImGui dictionaries from the authored UTF-8 catalogue."""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[2]
MARKER = '// BEGIN GENERATED LOCALIZATION\n'


def catalogue():
    rows = json.loads((ROOT / 'project/localization.json').read_text(encoding='utf-8'))
    seen = set()
    for row in rows:
        if len(row) != 5 or any(not isinstance(s, str) or not s or '\ufffd' in s for s in row):
            raise ValueError('Each translation needs five nonempty, valid Unicode strings')
        if row[0] in seen:
            raise ValueError('Duplicate translation: ' + row[0])
        seen.add(row[0])
        # Native printf placeholders must retain their count, type and order.
        placeholders = re.findall(r'%(?:\d+\$)?[-+.\d]*[a-zA-Z%]', row[0])
        if any(re.findall(r'%(?:\d+\$)?[-+.\d]*[a-zA-Z%]', text) != placeholders for text in row[1:]):
            raise ValueError('Changed format placeholders: ' + row[0])
    return sorted(rows, key=lambda row: row[0])


def outputs():
    rows = catalogue()
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    native = '// Generated by project/tools/generate_localization.py.\n'
    native += '\n'.join('  {' + ','.join(quote(s) for s in row) + '},' for row in rows) + '\n'
    launcher = ROOT / 'project/launcher/Launcher.cs'
    source = launcher.read_text(encoding='utf-8-sig').split(MARKER)[0].rstrip() + '\n\n'
    source += MARKER + '''namespace TableTennisLauncher {
    public static class UiText {
        public static string Code = "en";
        private static readonly string[][] Rows = {
'''
    source += '\n'.join('            new[]{' + ','.join(quote(s) for s in row) + '},' for row in rows)
    source += '''
        };
        private static readonly Dictionary<string,string[]> ByEnglish = new Dictionary<string,string[]>(StringComparer.Ordinal);
        private static readonly Dictionary<string,string> Original = new Dictionary<string,string>(StringComparer.Ordinal);
        static UiText() {
            foreach(var row in Rows) {ByEnglish.Add(row[0],row);Original[row[0]]=row[0];}
            foreach(var row in Rows) foreach(var text in row) if(!Original.ContainsKey(text)) Original.Add(text,row[0]);
        }
        public static string T(string text) {
            if(text==null) return null;
            string english;string[] row;
            if(!Original.TryGetValue(text,out english) || !ByEnglish.TryGetValue(english,out row)) return text;
            int index=Code=="fr"?1:Code=="de"?2:Code=="es"?3:Code=="it"?4:0;
            return row[index];
        }
        public static string Message(string text) {
            string exact=T(text);
            if(exact!=text || text==null) return exact;
            foreach(var row in Rows) if(row[0].Length>20 && text.Length>row[0].Length && text.StartsWith(row[0],StringComparison.Ordinal))
                return T(row[0])+T(text.Substring(row[0].Length));
            return text; // Preserve unknown technical details verbatim.
        }
    }
}
'''
    return {ROOT / 'project/src/localization_data.inc': native.encode('utf-8'),
            launcher: source.encode('utf-8-sig')}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, data in outputs().items():
        if args.check:
            # Git may normalize line endings on Windows checkouts.
            if not path.exists() or path.read_bytes().replace(b'\r\n',b'\n') != data:
                raise SystemExit('Regenerate localization: ' + str(path))
        else:
            path.write_bytes(data)
    print(f'Localization catalogue verified: {len(catalogue())} entries, five languages.')
